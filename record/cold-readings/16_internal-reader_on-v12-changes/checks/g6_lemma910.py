def s_basis_vec(f, n, q):
    """convert group-algebra element (t-monomials) to s-monomial coordinates, s = t+1 = t-1 over F_2:
    t^a = (1+s)^a = sum_b C(a,b) s^b mod 2"""
    out = {}
    for e in f:
        choices = [[b for b in range(a+1) if (math.comb(a, b) % 2)] for a in e]
        for bs in itertools.product(*choices):
            if bs in out: del out[bs]
            else: out[bs] = 1
    return out
def deg_order_index(n, q):
    mons = sorted(itertools.product(range(q), repeat=n), key=lambda e: (-sum(e), e))
    # bit position: higher bit = LOWER degree (so that pivot = highest bit = lowest-degree monomial)
    return {m: i for i, m in enumerate(mons)}, mons
for (k, q) in [(0, 2), (1, 2), (2, 2), (1, 4), (2, 4), (1, 8)]:
    n = 2*k + 1
    idx, mons = deg_order_index(n, q)
    def vec(sdict):
        v = 0
        for e in sdict: v ^= (1 << idx[e])
        return v
    # psi_J: J matching of {0..2k+1} with j_0 = 0; indices 1..2k+1 -> 0..2k here; factor (t_{k0}-1) and pairs avoiding 0
    psis = []
    for k0 in range(n):
        rest = [i for i in range(n) if i != k0]
        for Q in matchings(rest):
            psis.append(gen_g_P(Q, n, q, zero_partner=k0))
    def ideal_in_s(gs):
        # B = F_2[s]/(s^q) is spanned by the s-monomials, so (g)B = span{ g * s^m }
        S = Span()
        for g in gs:
            gsd = s_basis_vec(g, n, q)
            for m in itertools.product(range(q), repeat=n):
                prod = {}
                for e1 in gsd:
                    e3 = tuple(x+y for x, y in zip(e1, m))
                    if max(e3) < q:
                        if e3 in prod: del prod[e3]
                        else: prod[e3] = 1
                S.add(vec(prod))
        return S
    I = ideal_in_s(psis)
    # in(I): for each basis vector (pivot = lowest-degree monomial), its lowest-degree component
    def lowest_component(v):
        hb = v.bit_length() - 1; d = sum(mons[hb]); w = 0
        x = v
        while x:
            b = x.bit_length() - 1
            if sum(mons[b]) != d: break
            w |= (1 << b); x ^= (1 << b)
        return w
    # need reduced form so that pivots are distinct lowest monomials: Span pivots are distinct highest bits -> OK
    INI = Span()
    for v in I.piv.values(): INI.add(lowest_component(v))
    # (L_J)B: L_J = Y * D_J, D(a,b) = sum_{w=0}^{q-2} a^w b^{q-2-w} in s-variables
    Ls = []
    for k0 in range(n):
        rest = [i for i in range(n) if i != k0]
        for Q in matchings(rest):
            L = {tuple([1]*n): 1}
            for (a, b) in Q:
                Dd = {}
                for w in range(q-1):
                    e = [0]*n; e[a] = w; e[b] = q-2-w; Dd[tuple(e)] = 1
                newL = {}
                for e1 in L:
                    for e2 in Dd:
                        e3 = tuple(x+y for x, y in zip(e1, e2))
                        if max(e3) < q:
                            if e3 in newL: del newL[e3]
                            else: newL[e3] = 1
                L = newL
            Ls.append(L)
    LB = Span()
    for L in Ls:
        for m in itertools.product(range(q), repeat=n):
            prod = {}
            for e1 in L:
                e3 = tuple(x+y for x, y in zip(e1, m))
                if max(e3) < q: prod[e3] = 1
            LB.add(vec(prod))
    cont = all(INI.contains(v) for v in LB.piv.values())
    # control: in(I') for I' = I without one generator must NOT contain (L_J)B (when its dimension is smaller)
    Ip = ideal_in_s(psis[1:]) if len(psis) > 1 else None
    ctrl = None
    if Ip is not None:
        INIp = Span()
        for v in Ip.piv.values(): INIp.add(lowest_component(v))
        ctrl = all(INIp.contains(v) for v in LB.piv.values())
    r = q - 1
    target = N_r(2*k+2, r) if r >= 3 else 1
    print(f'  (k,q)=({k},{q}): dim I={I.dim()} dim in(I)={INI.dim()} dim (L_J)B={LB.dim()} N_r(2k+2)={target}  in(I) contains (L_J)B: {cont}  in(I)=(L_J)B: {cont and INI.dim()==LB.dim()}  control[in(I minus one psi) contains (L_J)B]: {ctrl}', flush=True)
