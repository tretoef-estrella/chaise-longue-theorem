def N_r(N, r):
    h = (r-1)//2; tot = 0
    for a in itertools.product(range(N//2+1), repeat=h):
        zc = N - 2*sum(a)
        if zc < 0: continue
        tot += math.factorial(N) // (math.factorial(zc) * math.prod(math.factorial(x)**2 for x in a))
    return tot

# --- group algebra elements as dicts {exponent tuple mod q: 1} over F_2 ---
def gmul(f, g, q):
    out = {}
    for a in f:
        for b in g:
            k = tuple((x+y) % q for x, y in zip(a, b))
            if k in out: del out[k]
            else: out[k] = 1
    return out
def gadd(f, g):
    out = dict(f)
    for k in g:
        if k in out: del out[k]
        else: out[k] = 1
    return out
def mono(n, idx_exp, q):
    e = [0]*n
    for i, x in idx_exp: e[i] = x % q
    return {tuple(e): 1}
def one(n): return {tuple([0]*n): 1}
def t_minus_1(i, n, q): return gadd(mono(n, [(i, 1)], q), one(n))
def phi(i, l, n, q):     # 1 + u + ... + u^{q-1}, u = t_i t_l
    out = {}
    for j in range(q): out = gadd(out, mono(n, [(i, j), (l, j)], q))
    return out

def enc(e, q):
    v = 0
    for x in e: v = v*q + x
    return v
def to_int(f, q):
    v = 0
    for e in f: v ^= (1 << enc(e, q))
    return v

class Span:
    def __init__(self): self.piv = {}
    def reduce(self, v):
        while v:
            hb = v.bit_length() - 1
            if hb in self.piv: v ^= self.piv[hb]
            else: return v
        return 0
    def add(self, v):
        v = self.reduce(v)
        if v: self.piv[v.bit_length()-1] = v; return True
        return False
    def dim(self): return len(self.piv)
    def contains(self, v): return self.reduce(v) == 0

def ideal_span(gens, n, q):
    S = Span()
    for g in gens:
        for nu in itertools.product(range(q), repeat=n):
            S.add(to_int(gmul(g, {nu: 1}, q), q))
    return S

def gen_g_P(P, n, q, zero_partner=None):
    """g_P = prod over pairs {i<l} of P of (t_l - 1) phi(t_i t_l); if zero_partner given, times (t_{k0} - 1)"""
    g = one(n)
    for (i, l) in P:
        g = gmul(g, gmul(t_minus_1(l, n, q), phi(i, l, n, q), q), q)
    if zero_partner is not None:
        g = gmul(g, t_minus_1(zero_partner, n, q), q)
    return g

