    w = closed_walks(N, h, False) if N % 2 == 0 else walks_to(N, h, False, [1] + [0] * (h - 1))
    for p in [3, 5, 7, 1000003, 2]:
        eodd = [red(elem_sym(N, j, r), p) for j in range(1, N + 1, 2)]
        dimE = sum(span_rank_ideal(box, eodd, p).values())
        print(f"  q={r} n={N} p={p}: dim ring = {r**N-dimE}  walks = {w}  equal: {r**N-dimE==w}", flush=True)
