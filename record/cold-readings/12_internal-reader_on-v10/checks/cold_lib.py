def series_I0(n):
    # I_0(2y) = sum y^{2b}/(b!)^2 up to degree n
    return [Fraction(1, factorial(i // 2) ** 2) if i % 2 == 0 else Fraction(0) for i in range(n + 1)]

def series_exp(n):
    return [Fraction(1, factorial(i)) for i in range(n + 1)]

def smul(a, b, n):
    c = [Fraction(0)] * (n + 1)
    for i, x in enumerate(a):
        if x == 0: continue
        for j, y in enumerate(b):
            if i + j > n: break
            c[i + j] += x * y
    return c

def closed_walks(n, h, loop):
    """n! [y^n] (e^y if loop) * I_0(2y)^h"""
    s = [Fraction(1)] + [Fraction(0)] * n
    if loop:
        s = smul(s, series_exp(n), n)
    for _ in range(h):
        s = smul(s, series_I0(n), n)
    v = s[n] * factorial(n)
    assert v.denominator == 1
    return int(v)

def walks_to(n, h, loop, target):
    """number of walks of length n on Z^h from 0 to target with steps +-e_i (and 0 if loop)."""
    from collections import Counter
    cur = Counter({tuple([0] * h): 1})
    steps = []
    for i in range(h):
        for s in (1, -1):
            e = [0] * h; e[i] = s; steps.append(tuple(e))
    if loop:
        steps.append(tuple([0] * h))
    for _ in range(n):
        nxt = Counter()
        for pnt, c in cur.items():
            for s in steps:
                nxt[tuple(a + b for a, b in zip(pnt, s))] += c
        cur = nxt
    return cur.get(tuple(target), 0)
