        R = Box(m, p); R2 = Box(m - 1, p)
        for J in range(0, m + 1):
            E, piv = R.span(gens(R, m, J)); dim = len(piv); z = ZC[m, J]
            ok = (dim == z); line = f"p={p} m={m} J={J}: dim I = {dim}, |Z| = {z}"
            if J < m:
                W = slices(R, E)
                want = [(0, J - 1), (1, J), (2, J + 1)] if J >= 1 else [(2, 1)]
                for j, Jt in want:
                    inside = all(R2.member(W[j][0], W[j][1], g) for g in gens(R2, m - 1, Jt)); nS += 1
