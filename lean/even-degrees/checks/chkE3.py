print("(C) the identities and witnesses of the proof (over F_10007, m = 5; index 1 of the file is index 0 here)")
R = Box(5, 10007); y = [R.var(i) for i in range(5)]; P = R.p
sub = lambda A, B: (A - B) % P
for (a, b, c) in [(1, 2, 3), (1, 3, 4), (2, 3, 4)]:
    lhs = R.var(c, 2); rhs = (R.mul(y[0], sub(y[c], y[0])) + R.D(0, c)) % P
    rec(np.array_equal(lhs, rhs), "y_c^2 identity")
    V = R.mul(R.mul(sub(y[b], y[a]), sub(y[c], y[a])), sub(y[c], y[b]))
    rhs = (R.mul(R.D(0, a), sub(y[c], y[b])) - R.mul(R.D(0, b), sub(y[c], y[a])) + R.mul(R.D(0, c), sub(y[b], y[a]))) % P
    rec(np.array_equal(V, rhs), "Vandermonde identity")
    lhs = sub(R.D(0, b), R.D(0, a)); rhs = (-R.mul(y[0], sub(y[b], y[a])) + sub(R.var(b, 2), R.var(a, 2))) % P
    rec(np.array_equal(lhs, rhs), "D(1,b) - D(1,a) identity")
    V1 = R.mul(R.mul(sub(y[a], y[0]), sub(y[b], y[0])), sub(y[b], y[a]))     # Delta(y_1, y_a, y_b)
    coef2 = V1[2].reshape(-1); want = sub(y[b], y[a])[0].reshape(-1)
    rec(np.array_equal(coef2, want), "y_1^2-coefficient of Delta(y_1,y_a,y_b)")
print("  y_c^2 = y_1(y_c - y_1) + D(1,c);  Delta(a,b,c) = D(1,a)(y_c-y_b) - D(1,b)(y_c-y_a) + D(1,c)(y_b-y_a);")
