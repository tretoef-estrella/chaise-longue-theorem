print("(D) (iv)-(vi): the ideal of the matchings and the number")
def Qe4(k):   # 1 + sum_c C(2k+2, 2c) * C(2(k-c)+2, k-c+1)  (q_even_count.md (i), with Q_j(3) = C(2j+2, j+1))
    from math import comb
    return 1 + sum(comb(2*k + 2, 2*c) * comb(2*(k - c) + 2, k - c + 1) for c in range(k + 1))
for k in (0, 1, 2):
    m = 2*k + 1
    for p in (2, 3, 5):
        R = Box(m, p)
        # D_J over the matchings J of {0..2k+1} (index 0 is the extra point; variables are 1..2k+1 -> 0..2k here)
        DJ = []
        for J in matchings(list(range(2*k + 2)), k + 1):
            DJ.append(R.DP([(a - 1, b - 1) for a, b in J if a != 0]))
        E1, p1 = R.span(DJ); E2, p2 = R.span(gens(R, m, 1))
        same = (p1 == p2) and np.array_equal(E1, E2)
        z1 = ZC[m, 1]; zero_sum = sum(1 for M in itertools.product((-1, 0, 1), repeat=2*k + 2) if sum(M) == 0)
        ok = same and len(p1) == z1 == zero_sum == Qe4(k)
        rec(ok, f"k={k} p={p}")
        print(f"  k={k} p={p}: (D_J) = I({m},1): {same}; dim = {len(p1)}; |Z_1| = {z1}; tuples of sum 0 = {zero_sum}; Qe_k(4) = {Qe4(k)}", flush=True)

