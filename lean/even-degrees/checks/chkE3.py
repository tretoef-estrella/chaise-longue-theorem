# Piece E3 checks (q_odd3.md): the odd box r = 3.  Box ring F_p[y_1..y_m]/(y_i^3), D(a,b) = a^2 - ab + b^2.
# (A) the count recursion of (i);  (B) dim I(m,J) against |Z_J^(m)| and the slice inclusions of (ii), on the computed slices;
# (C) the two identities of Case II, J = 1, and the explicit witnesses;  (D) (iv)-(vi): the generators of I(2k+1,1) are the D_J, and the number;
# (E) controls that can fail: a slice one step too low; I(m,0) without its Vandermonde generators; the wrong sign in D.
# The engine is the auditor's gate of 2 Oct (corpus4/regla298_sky/auditoria_T3.py), with an incremental span.
import sys, itertools
import numpy as np

def matchings(S, k):
    S = list(S)
    if k == 0: yield (); return
    if len(S) < 2 * k: return
    a = S[0]; rest = S[1:]
    for i, b in enumerate(rest):
        for M in matchings(rest[:i] + rest[i+1:], k - 1): yield ((a, b),) + M
    yield from matchings(rest, k)

class Box:
    def __init__(s, m, p, sign=-1): s.m, s.p, s.N, s.sign = m, p, 3 ** m, sign
    def mono(s, exps):
        A = np.zeros((3,) * s.m, dtype=np.int64); A[tuple(exps)] = 1; return A
    def var(s, i, e=1):
        x = [0] * s.m; x[i] = e; return s.mono(x)
    def mul(s, A, B):
        C = np.zeros_like(A)
        for idx in zip(*np.nonzero(B)):
            c = B[idx]; src = tuple(slice(0, 3 - d) for d in idx); dst = tuple(slice(d, 3) for d in idx)
            C[dst] += c * A[src]
        return C % s.p
    def D(s, a, b): return (s.var(a, 2) + s.sign * s.mul(s.var(a), s.var(b)) + s.var(b, 2)) % s.p
    def DP(s, P):
        A = s.mono([0] * s.m)
        for a, b in P: A = s.mul(A, s.D(a, b))
        return A
    def echelon(s, M):
        p = s.p; r = 0; piv = []
        for c in range(M.shape[1]):
            nz = np.flatnonzero(M[r:, c])
            if len(nz) == 0: continue
            i = nz[0] + r
            if i != r: M[[r, i]] = M[[i, r]]
            M[r] = (M[r] * pow(int(M[r, c]), -1, p)) % p
            o = np.flatnonzero(M[:, c]); o = o[o != r]
            if len(o): M[o] = (M[o] - M[o, c][:, None] * M[r][None, :]) % p
            piv.append(c); r += 1
            if r == M.shape[0]: break
        return M[:r], piv
    def span(s, gens):                     # reduced echelon basis of the ideal generated by gens, one generator at a time
        E = np.zeros((0, s.N), dtype=np.int64); piv = []
        for g in gens:
            rows = []
            for idx in itertools.product(range(3), repeat=s.m):
                src = tuple(slice(0, 3 - d) for d in idx); dst = tuple(slice(d, 3) for d in idx)
                C = np.zeros_like(g); C[dst] = g[src]
                if C.any(): rows.append(C.reshape(-1))
            if not rows: continue
            M = np.array(rows, dtype=np.int64) % s.p
            if len(piv): M = (M - np.rint(M[:, piv].astype(np.float64) @ E.astype(np.float64)).astype(np.int64)) % s.p   # entries < p^2 * 729: exact in float64
            M = M[M.any(axis=1)]
            if len(M) == 0: continue
            E, piv = s.echelon(np.vstack([E, M]))
        return E, piv
    def member(s, E, piv, v):
        v = v.reshape(-1) % s.p
        if len(piv): v = (v - v[piv] @ E) % s.p
        return not v.any()

def gens(R, m, J, vand=True):              # generators of I(m,J), as in the Setting of q_odd3.md
    idx = list(range(m)); out = []
    if J >= m: return [R.mono([0] * R.m)]
    if (m - J) % 2 == 0:
        for P in matchings(idx, (m - J) // 2): out.append(R.DP(P))
    elif J >= 1:
        p = (m - 1 - J) // 2
        for P in matchings(idx, p):
            used = {x for pr in P for x in pr}; free = [x for x in idx if x not in used]
            for a, b in itertools.combinations(free, 2): out.append(R.mul((R.var(b) - R.var(a)) % R.p, R.DP(P)))
        for P in matchings(idx, p + 1): out.append(R.DP(P))
    else:
        for c in idx:
            rest = [x for x in idx if x != c]
            for P in matchings(rest, len(rest) // 2): out.append(R.mul(R.var(c, 2), R.DP(P)))
        if vand:
            for a, b, c in itertools.combinations(idx, 3):
                rest = [x for x in idx if x not in (a, b, c)]
                V = R.mul(R.mul((R.var(b) - R.var(a)) % R.p, (R.var(c) - R.var(a)) % R.p), (R.var(c) - R.var(b)) % R.p)
                for P in matchings(rest, len(rest) // 2): out.append(R.mul(V, R.DP(P)))
    return out

def Zcount(m, J): return sum(1 for M in itertools.product((-1, 0, 1), repeat=m) if abs(sum(M)) <= J)

def slices(R, E):                           # W_0, W_1, W_2 (peeling the first variable), as echelon bases in the box of the others
    m = R.m; out = []; T = E.reshape((-1,) + (3,) * m); R2 = Box(m - 1, R.p); n1 = 3 ** (m - 1)
    M = np.concatenate([T[:, d].reshape(len(T), -1) for d in (2, 1, 0)], axis=1) % R.p
    Ech, piv = R2.echelon(M.copy()) if len(M) else (M, [])
    for j in range(3):
        blk = 2 - j
        rows = [row[blk * n1:(blk + 1) * n1] for row, pc in zip(Ech, piv) if pc // n1 == blk]
        W = np.array(rows, dtype=np.int64).reshape(-1, n1) if rows else np.zeros((0, n1), dtype=np.int64)
        out.append(R2.echelon(W.copy()) if len(W) else (W, []))
    return out

checks = bad = 0
def rec(ok, line):
    global checks, bad
    checks += 1; bad += (not ok)
    if not ok: print("  FAIL " + line, flush=True)

